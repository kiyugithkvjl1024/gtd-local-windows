const assert=require('node:assert/strict');
const c=require('../webapp/static/local-calendar.js');
assert.equal(typeof c.layoutTimed,'function','calendar must expose common proportional layout');
const day='2026-10-09';
const event=(start,end)=>({start:day+'T'+start+':00+09:00',end:day+'T'+end+':00+09:00'});
let rows=c.layoutTimed([event('09:00','09:22'),event('00:00','06:00'),event('09:10','10:00')],day);
assert.equal(rows[0].top,540);assert.equal(rows[0].height,22);assert.equal(rows[1].height,360);
assert.equal(rows[0].columns,2);assert.equal(rows[2].lane,1);assert.equal(rows[1].columns,1);
assert.deepEqual(c.layoutTimed([],day),[]);
assert.equal(c.layoutTimed([{start:'2026-10-08T15:00:00Z',end:'2026-10-09T15:00:00Z'}],day)[0].height,1440);
assert.deepEqual(c.moveInterval(event('23:00','23:30'),'move',90),{start:'2026-10-09T15:30:00.000Z',end:'2026-10-09T16:00:00.000Z'});
assert.throws(()=>c.moveInterval(event('09:00','09:22'),'start',25));
const entity={id:'sample',content_hash:'fresh',frontmatter:{title:'Example',status:'done',scheduled_start:day+'T09:00:00+09:00',scheduled_end:day+'T10:00:00+09:00'}};
const op=c.intervalOperation(entity,'actual',event('10:00','10:22'));
assert.equal(op.action,'correct_work_session');assert.equal(op.work_started_at,day+'T10:00:00+09:00');assert.equal(op.fields,undefined);
const plan=c.intervalOperation({...entity,frontmatter:{...entity.frontmatter,status:'scheduled'}},'planned',event('11:00','12:00'));
assert.equal(plan.fields.scheduled_start,day+'T11:00:00+09:00');assert.equal(plan.fields.work_started_at,undefined);assert.equal(plan.fields.action_date,day);
assert.throws(()=>c.intervalOperation(entity,'planned',event('11:00','12:00')));
console.log('Common axis proportional height, overlaps, timezone, midnight and explicit edit target: passed');
assert.equal(typeof c.ensureFreshInterval,'function','drag must bind to the entity version it started from');
assert.throws(()=>c.ensureFreshInterval({content_hash:'new'}, {content_hash:'old'}));
assert.doesNotThrow(()=>c.ensureFreshInterval({content_hash:'same'},{content_hash:'same'}));
